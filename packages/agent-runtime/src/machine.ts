export type State =
  | "RECEIVED" | "PREFLIGHT" | "CONTRACT_READY" | "PLANNING" | "AWAITING_PLAN_APPROVAL"
  | "CONTEXT_READY" | "IMPLEMENTING" | "VERIFYING" | "REVIEWING" | "AWAITING_ACCEPTANCE"
  | "ACCEPTED" | "DIAGNOSING" | "BOUNDED_REPAIR" | "NEEDS_INPUT" | "BLOCKED" | "ESCALATED" | "CANCELLED";

const NEXT: Record<string, State[]> = {
  RECEIVED: ["PREFLIGHT"],
  PREFLIGHT: ["CONTRACT_READY"],
  CONTRACT_READY: ["PLANNING", "CONTEXT_READY"],
  PLANNING: ["AWAITING_PLAN_APPROVAL"],
  AWAITING_PLAN_APPROVAL: ["CONTEXT_READY"],
  CONTEXT_READY: ["IMPLEMENTING"],
  IMPLEMENTING: ["VERIFYING"],
  VERIFYING: ["REVIEWING", "AWAITING_ACCEPTANCE", "DIAGNOSING"],
  REVIEWING: ["AWAITING_ACCEPTANCE", "DIAGNOSING"],
  AWAITING_ACCEPTANCE: ["ACCEPTED", "IMPLEMENTING"], // an edit after verification re-enters implementing
  DIAGNOSING: ["BOUNDED_REPAIR"],
  BOUNDED_REPAIR: ["VERIFYING"],
};
const TERMINAL: State[] = ["NEEDS_INPUT", "BLOCKED", "ESCALATED", "CANCELLED"];
const DONE: State[] = ["ACCEPTED", ...TERMINAL];

export function canMove(from: State, to: State): boolean {
  if (DONE.includes(from)) return false;
  return TERMINAL.includes(to) || (NEXT[from]?.includes(to) ?? false);
}
